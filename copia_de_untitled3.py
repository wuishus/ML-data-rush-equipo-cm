from collections import Counter

demanda = Counter()

for archivo in archivos:
    for bloque in pd.read_csv(
        archivo,
        usecols=["started_at", "start_station_name"],
        chunksize=100000
    ):
        bloque["started_at"] = pd.to_datetime(
            bloque["started_at"], errors="coerce"
        )

        bloque = bloque.dropna(
            subset=["started_at", "start_station_name"]
        )

        bloque["fecha"] = bloque["started_at"].dt.date
        bloque["hora"] = bloque["started_at"].dt.hour

        conteos = bloque.groupby(
            ["fecha", "hora", "start_station_name"]
        ).size()

        demanda.update(conteos.to_dict())

